# 4. FIGURE 3: MINORITY RECALL BAR CHART @ 40% ASYM NOISE
# ======================================================================
def generate_figure_recall_bar(df):
    sub = df[(df["noise_type"] == "asym") & (df["noise_rate"] == 0.4)]
    model_order = [
        ("mlp_ccr",          "CCR (Ours)",      C_CCR),
        ("mlp_weighted_ce",  "Weighted CE",     C_WCE),
        ("mlp_smote",        "SMOTE",           "#8b5cf6"),
        ("mlp_standard",     "Standard CE",     C_CE),
        ("mlp_focal",        "Focal Loss",      C_FOCAL),
        ("xgboost_default",  "XGBoost",         C_XGB),
        ("ft_transformer",   "FT-Transformer",  C_FTT),
        ("lightgbm_default", "LightGBM",        C_LGBM),
        ("tabnet",           "TabNet",          C_TABNET),
    ]

    names, means, stds, colors = [], [], [], []
    for k, name, c in model_order:
        m = sub[sub["model"] == k]["minority_recall"].mean()
        s = sub[sub["model"] == k]["minority_recall"].std()
        names.append(name)
        means.append(m)
        stds.append(s if pd.notna(s) else 0.02)
        colors.append(c)

    fig, ax = plt.subplots(figsize=(8.5, 5.2), dpi=600)
    bars = ax.bar(range(len(names)), means, yerr=stds, capsize=4,
                  color=colors, edgecolor="#1e293b", linewidth=0.9,
                  alpha=0.9, width=0.62)

    for bar in bars:
        yval = bar.get_height()
        ax.text(bar.get_x() + bar.get_width() / 2, yval + 0.025,
                f"{yval:.3f}", ha="center", va="bottom",
                fontsize=10, fontweight="bold")

    ax.set_xticks(range(len(names)))
    ax.set_xticklabels(names, rotation=30, ha="right", fontsize=11)
    ax.set_ylabel(r"Minority Class Recall ($\mathrm{Recall}_1$)",
                  fontweight="bold")
    ax.set_ylim(0, 0.92)
    plt.tight_layout(pad=0.25)
    plt.savefig(FIG_DIR / "fig3_minority_recall.pdf")
    plt.savefig(FIG_DIR / "fig3_minority_recall.png", dpi=600)
    plt.close()
    print("[DONE] Generated Minority Recall Bar Chart (fig3)")


